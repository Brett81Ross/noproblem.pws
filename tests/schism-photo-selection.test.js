'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const photos=require('../photo-selection.js');
const synthetic=Array.from({length:24},(_,i)=>'data:image/jpeg;base64,'+Buffer.from('synthetic_photo_'+String(i).padStart(3,'0')).toString('base64'));
const evidence=Array.from({length:24},(_,i)=>({kind:'photo',source:'operator_upload',capturedAt:'synthetic_'+i}));
assert.deepEqual(photos.defaultIndices(3,8),[0,1,2]);
assert.deepEqual(photos.defaultIndices(8,8),[0,1,2,3,4,5,6,7]);
assert.deepEqual(photos.defaultIndices(24,8),[0,3,7,10,13,16,20,23]);
assert.deepEqual(photos.defaultIndices(24,4),[0,8,15,23]);
assert.throws(()=>photos.defaultIndices(25,8),/Invalid photo capacity/);
let selection=photos.defaultIndices(24,8);
let plan=photos.compile(synthetic,evidence,selection,8,false);
assert.equal(plan.ok,false,'no consent means no AI call');
plan=photos.compile(synthetic,evidence,selection,8,true);
assert.equal(plan.ok,true);
assert.equal(plan.images.length,8);
assert.deepEqual(plan.photoSelection.selectedSlots,[1,4,8,11,14,17,21,24]);
assert.deepEqual(plan.evidenceMeta.map(x=>x.capturedAt),
  ['synthetic_0','synthetic_3','synthetic_7','synthetic_10','synthetic_13','synthetic_16','synthetic_20','synthetic_23']);
assert.equal(plan.photoSelection.operatorConfirmed,true);
assert.equal(photos.matchesCoverage({stagedCount:24,submittedCount:8,omittedCount:16,
 selectedSlots:plan.photoSelection.selectedSlots,operatorConfirmed:true},plan.photoSelection),true);
assert.equal(photos.matchesCoverage({stagedCount:24,submittedCount:8,omittedCount:16,
 selectedSlots:[1,2,3,4,5,6,7,8],operatorConfirmed:true},plan.photoSelection),false);
assert.equal(photos.matchesCoverage(null,plan.photoSelection),false);
assert.equal(photos.compile(synthetic,evidence,[1,1],8,true).ok,false);
assert.equal(photos.compile(synthetic,evidence,[-1,2],8,true).ok,false);
assert.equal(photos.compile(synthetic,evidence,[24],8,true).ok,false);
assert.equal(photos.compile(synthetic,evidence,[],8,true).ok,false);
assert.equal(photos.compile(synthetic,evidence,Array.from({length:9},(_,i)=>i),8,true).ok,false);
assert.equal(photos.toggleIndices(selection,1,24,8).ok,false,'must deselect at 8 cap');
selection=photos.toggleIndices(selection,0,24,8).indices;
selection=photos.toggleIndices(selection,1,24,8).indices;
assert.deepEqual(selection,[1,3,7,10,13,16,20,23]);
assert.deepEqual(photos.compile(synthetic,evidence,selection,8,true).photoSelection.selectedSlots,[2,4,8,11,14,17,21,24]);
const legacy=photos.compile(synthetic,evidence,photos.defaultIndices(24,4),4,true);
assert(legacy.ok&&legacy.images.length===4&&legacy.photoSelection.stagedCount===24);
assert(!photos.compile(synthetic,evidence,photos.defaultIndices(24,4),4,false).ok);
const short=photos.compile(synthetic.slice(0,3),evidence.slice(0,3),[],8,false);
assert(short.ok&&short.images.length===3);
assert.equal(short.photoSelection.operatorConfirmed,false);
assert(!photos.compile(synthetic.slice(0,3),evidence,[0],8,false).photoSelection.operatorConfirmed);
assert(!photos.compile([null],[],[0],8,false).ok);
for(const file of ['index.html','runtime/base-shell.html']){
 const content=fs.readFileSync(path.join(__dirname,'..',file),'utf8');
 assert(content.includes('/photo-selection.js'),file+' missing shared selector');
 assert(content.includes('schismPhotoReview.preflight()'),file+' must preflight before fetch');
 assert(!content.includes("stagedBase64Images.slice(0, 8)"),file+' cannot silently truncate 8');
 assert(!content.includes("stagedBase64Images.slice(0, 4)"),file+' cannot silently truncate 4');
}
const quick=fs.readFileSync(path.join(__dirname,'../quick-quote.js'),'utf8');
assert(quick.includes('photoEvidencePayload(payload.photoSelection && payload.photoSelection.selectedSlots)'), 'QuickQuote must not label omitted photos as AI evidence');
const index=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(index.includes('currentAnalysisInputSignature()!==requestSignature'),'stale analysis responses must fail closed');
assert(index.includes('window.__schismReleaseState={locked:true,reason:'),'analysis pending must lock crew release');
assert(index.includes('matchesCoverage(data.rawMatrixData?.photoCoverage'),'model response must match selected photos');
assert(index.includes('invalidatePhotoApproval('),'photo changes must invalidate released job');
const legacyShell=fs.readFileSync(path.join(__dirname,'../runtime/base-shell.html'),'utf8');
assert(legacyShell.includes('legacyAnalysisInputSignature()!==requestSignature'),'legacy analysis cannot accept stale photo sets');
assert(legacyShell.includes('matchesCoverage(data.rawMatrixData?.photoCoverage'),'legacy response must match four-photo evidence');
console.log('Schism 24-photo selection, evidence correspondence, no-extra-request QA passed');
