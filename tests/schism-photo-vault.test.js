'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vault=require('../photo-vault.js');
const image='data:image/jpeg;base64,'+Buffer.from('jpeg-test').toString('base64');
vault.checkPhotos([image],[{source:'operator_upload'}]);
assert.throws(()=>vault.checkPhotos([image],[]),/not aligned/);
assert.throws(()=>vault.checkPhotos(Array(25).fill(image),Array(25).fill({})),/not aligned/);
assert.throws(()=>vault.checkPhotos(['data:image/png;base64,aGVsbG8='],[{}]),/invalid/);
assert.throws(()=>vault.checkPhotos([image],[null]),/provenance/);
vault.validateKey('quote:est_test_123:r1');
vault.validateKey('crew:release_123');
assert.throws(()=>vault.validateKey('../path'),/Invalid evidence/);
assert.throws(()=>vault.validateKey('quote:a/b'),/Invalid evidence/);
assert.throws(()=>vault.verifyReceipt({key:'crew:release_123',count:3,digest:'bad'}),/invalid/);
vault.verifyReceipt({key:'quote:est_1:r1',count:3,digest:'sha256:'+'f'.repeat(64)});
const index=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
assert(index.includes('<script src="/photo-vault.js"></script>'), 'photo vault is not loaded');
assert(index.includes('window.SchismPhotoVault.save('),'photo evidence is never durably saved');
assert(index.includes('window.SchismPhotoVault.load('),'stored photo evidence is not validated on restore');
assert(index.includes('verifiedCrewPhotoReceipt'), 'Crew Command must gate new releases on recovered photo evidence');
assert(index.includes('projectLoadSequence'), 'overlapping project reopen requests must not mix evidence');
assert(index.includes('photoVault:')===false, 'photoVault receipt is stored only after confirmed IndexedDB success');
console.log('Schism local evidence vault validation and recovery contract QA passed');
